CREATE FUNCTION reject_rule_version_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- A published version may disappear only as part of deleting its parent rule.
    IF TG_OP = 'DELETE'
       AND NOT EXISTS (SELECT 1 FROM download_rule WHERE id = OLD.rule_id) THEN
        RETURN OLD;
    END IF;

    RAISE EXCEPTION 'published rule versions are immutable'
        USING ERRCODE = '55000';
END;
$$;

CREATE TRIGGER rule_version_immutable
BEFORE UPDATE OR DELETE ON rule_version
FOR EACH ROW
EXECUTE FUNCTION reject_rule_version_mutation();

