CREATE TABLE job (
    id UUID PRIMARY KEY,
    priority_class TEXT NOT NULL CHECK (priority_class IN (
        'immediate',
        'manual_import',
        'scheduled_collection',
        'background_maintenance'
    )),
    kind TEXT NOT NULL CONSTRAINT job_kind_check CHECK (kind IN (
        'scheduled_collection',
        'ranking_collection',
        'following_collection',
        'bookmarks_collection',
        'import_artist',
        'import_work',
        'download_media',
        'generate_derivative',
        'purge_trash'
    )),
    payload JSONB NOT NULL,
    state TEXT NOT NULL CONSTRAINT job_state_check CHECK (state IN (
        'queued',
        'running',
        'waiting_account',
        'waiting_storage',
        'completed',
        'failed',
        'cancelled'
    )),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    lease_owner UUID,
    lease_expires_at TIMESTAMPTZ,
    error_class TEXT,
    retryable BOOLEAN,
    next_retry_at TIMESTAMPTZ,
    resource_revision BIGINT NOT NULL DEFAULT 1 CHECK (resource_revision > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    pixiv_account_id UUID REFERENCES pixiv_account(id) ON DELETE SET NULL,
    retryable_failure_count INTEGER NOT NULL DEFAULT 0 CHECK (retryable_failure_count >= 0),
    CONSTRAINT job_running_lease_check
        CHECK ((state = 'running') = (lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL)),
    CONSTRAINT job_retry_time_check CHECK (next_retry_at IS NULL OR state = 'failed'),
    CONSTRAINT job_waiting_account_check CHECK (
        state <> 'waiting_account'
        OR (
            pixiv_account_id IS NOT NULL
            AND lease_owner IS NULL
            AND lease_expires_at IS NULL
            AND next_retry_at IS NULL
        )
    ),
    CONSTRAINT job_waiting_storage_check CHECK (
        state <> 'waiting_storage'
        OR (
            kind IN ('download_media', 'generate_derivative')
            AND lease_owner IS NULL
            AND lease_expires_at IS NULL
            AND next_retry_at IS NULL
        )
    )
);

CREATE INDEX job_claim_runnable_idx
    ON job (priority_class, available_at, next_retry_at, created_at)
    WHERE state IN ('queued', 'failed', 'running');

CREATE INDEX job_waiting_account_idx
    ON job (pixiv_account_id, updated_at)
    WHERE state = 'waiting_account';

CREATE INDEX job_waiting_storage_idx
    ON job (updated_at)
    WHERE state = 'waiting_storage';

CREATE UNIQUE INDEX job_one_active_trash_purge_idx
    ON job ((payload ->> 'work_id'))
    WHERE kind = 'purge_trash'
      AND (
          state IN ('queued', 'running', 'waiting_account')
          OR (state = 'failed' AND retryable = true)
      );

